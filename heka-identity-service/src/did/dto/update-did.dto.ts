import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger'
import { Type } from 'class-transformer'
import {
  ArrayMaxSize,
  IsArray,
  IsIn,
  IsOptional,
  IsString,
  IsUrl,
  Matches,
  MaxLength,
  ValidateNested,
} from 'class-validator'

import { VERIFICATION_PURPOSES, VerificationPurpose } from 'common/did-registrar'

// A relative DID URL fragment, such as `#key-1`
const FRAGMENT = /^#[A-Za-z0-9._~-]{1,64}$/
const FRAGMENT_MESSAGE = '$property must be a relative fragment such as #key-1 (letters, digits, . _ ~ -; at most 64)'

export const MAX_DID_UPDATE_OPERATIONS = 10

export const DEFAULT_VERIFICATION_PURPOSES: VerificationPurpose[] = ['assertionMethod', 'authentication']

export class AddServiceDto {
  @ApiProperty({ example: '#svc-1', description: 'Relative fragment of the service id' })
  @IsString()
  @Matches(FRAGMENT, { message: FRAGMENT_MESSAGE })
  public id!: string

  @ApiProperty({
    example: 'LinkedDomains',
    description:
      'Service type. did:indybesu accepts LinkedDomains, DIDCommMessaging, CredentialRegistry, OID4VCI and OID4VP only',
  })
  @IsString()
  @MaxLength(100)
  public type!: string

  @ApiProperty({ example: 'https://example.com' })
  @IsUrl({ require_tld: false })
  public serviceEndpoint!: string
}

export class AddVerificationMethodDto {
  @ApiPropertyOptional({
    example: '#key-1',
    description: 'Relative fragment of the verification method id. Defaults to the lowest unused #key-<n>',
  })
  @IsOptional()
  @IsString()
  @Matches(FRAGMENT, { message: FRAGMENT_MESSAGE })
  public id?: string

  @ApiPropertyOptional({
    enum: VERIFICATION_PURPOSES,
    isArray: true,
    default: DEFAULT_VERIFICATION_PURPOSES,
    description: 'Verification relationships that reference the new key',
  })
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(VERIFICATION_PURPOSES.length)
  @IsIn(VERIFICATION_PURPOSES, { each: true })
  public purposes?: VerificationPurpose[]
}

/**
 * Changes to a DID document: between 1 and `MAX_DID_UPDATE_OPERATIONS` operations over all arrays (checked by
 * `DidService`, as the fields are each optional). Keys of added verification methods are generated by the Identity
 * Service (Ed25519); no field takes key material.
 */
export class UpdateDidRequestDto {
  @ApiPropertyOptional({ type: [AddServiceDto] })
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(MAX_DID_UPDATE_OPERATIONS)
  @ValidateNested({ each: true })
  @Type(() => AddServiceDto)
  public addServices?: AddServiceDto[]

  @ApiPropertyOptional({ type: [String], example: ['#svc-1'], description: 'Fragments of services to remove' })
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(MAX_DID_UPDATE_OPERATIONS)
  @IsString({ each: true })
  @Matches(FRAGMENT, { each: true, message: FRAGMENT_MESSAGE })
  public removeServices?: string[]

  @ApiPropertyOptional({ type: [AddVerificationMethodDto] })
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(MAX_DID_UPDATE_OPERATIONS)
  @ValidateNested({ each: true })
  @Type(() => AddVerificationMethodDto)
  public addVerificationMethods?: AddVerificationMethodDto[]

  @ApiPropertyOptional({
    type: [String],
    example: ['#key-1'],
    description: 'Fragments of verification methods to remove, with every reference to them',
  })
  @IsOptional()
  @IsArray()
  @ArrayMaxSize(MAX_DID_UPDATE_OPERATIONS)
  @IsString({ each: true })
  @Matches(FRAGMENT, { each: true, message: FRAGMENT_MESSAGE })
  public removeVerificationMethods?: string[]
}
