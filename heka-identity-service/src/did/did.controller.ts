import { Body, Controller, Get, HttpCode, Param, Patch, Post, Query, UseGuards, UseInterceptors } from '@nestjs/common'
import {
  ApiBadRequestResponse,
  ApiBearerAuth,
  ApiBody,
  ApiConflictResponse,
  ApiCreatedResponse,
  ApiExtraModels,
  ApiForbiddenResponse,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiParam,
  ApiServiceUnavailableResponse,
  ApiTags,
  ApiUnauthorizedResponse,
  ApiUnprocessableEntityResponse,
} from '@nestjs/swagger'

import { ReqTenantAgent, TenantAgent, TenantAgentInterceptor } from 'common/agent'
import { AuthInfo, JwtAuthGuard, ReqAuthInfo, Role } from 'common/auth'
import { AnyRole, RoleGuard, Roles } from 'common/authz'
import { InjectLogger, Logger } from 'common/logger'

import { DidService } from './did.service'
import {
  CreateDidRequestDto,
  DidDocumentDto,
  DidMethodCapabilitiesDto,
  FindDidRequestDto,
  GetDidMethodsResponseDto,
  UpdateDidRequestDto,
} from './dto'

@ApiTags('Dids')
@ApiExtraModels(DidMethodCapabilitiesDto)
@ApiBearerAuth()
@Controller('dids')
@UseGuards(JwtAuthGuard, RoleGuard)
export class DidController {
  public constructor(
    @InjectLogger(DidController)
    private readonly logger: Logger,
    private readonly didService: DidService,
  ) {
    this.logger.child('constructor').trace('<>')
  }

  @ApiOperation({ summary: 'Get supported DIDs methods' })
  @ApiOkResponse({ description: 'DID methods', type: GetDidMethodsResponseDto })
  @ApiBadRequestResponse({ description: 'Bad Request' })
  @ApiUnauthorizedResponse({ description: 'Unauthorized' })
  @AnyRole()
  @Get('/methods')
  @UseInterceptors(TenantAgentInterceptor)
  public getMethods(): GetDidMethodsResponseDto {
    const logger = this.logger.child('getMethods')
    logger.trace('>')

    const res = this.didService.getMethods()

    logger.trace({ res }, '<')
    return res
  }

  @ApiOperation({ summary: 'Get DIDs' })
  @ApiOkResponse({ description: 'DID documents', type: [DidDocumentDto] })
  @ApiBadRequestResponse({ description: 'Bad Request' })
  @ApiUnauthorizedResponse({ description: 'Unauthorized' })
  @AnyRole()
  @Get()
  @UseInterceptors(TenantAgentInterceptor)
  public async find(
    @ReqTenantAgent() tenantAgent: TenantAgent,
    @Query() req: FindDidRequestDto,
  ): Promise<DidDocumentDto[]> {
    const logger = this.logger.child('find', req)
    logger.trace('>')

    const res = await this.didService.find(tenantAgent, req)

    logger.trace({ res }, '<')
    return res
  }

  @ApiOperation({ summary: 'Create a new public DID' })
  @ApiBody({ type: CreateDidRequestDto })
  @ApiCreatedResponse({ description: 'Created DID document', type: DidDocumentDto })
  @ApiBadRequestResponse({ description: 'Bad Request' })
  @ApiUnauthorizedResponse({ description: 'Unauthorized' })
  @ApiConflictResponse({ description: 'Conflict' })
  @ApiUnprocessableEntityResponse({ description: 'Unprocessable Entity' })
  @Post()
  @Roles(Role.Admin, Role.OrgAdmin, Role.Issuer, Role.Verifier)
  public async create(@ReqAuthInfo() authInfo: AuthInfo, @Body() req: CreateDidRequestDto): Promise<DidDocumentDto> {
    const logger = this.logger.child('create', { authInfo })
    logger.trace('>')

    const res = this.didService.create(authInfo, req)

    logger.trace({ res }, '<')
    return res
  }

  @ApiOperation({ summary: 'Resolve a DID' })
  @ApiParam({ name: 'did', type: String })
  @ApiOkResponse({ description: 'DID document', type: DidDocumentDto })
  @ApiUnauthorizedResponse({ description: 'Unauthorized' })
  @ApiNotFoundResponse({ description: 'Not Found' })
  @AnyRole()
  @Get(':did')
  @UseInterceptors(TenantAgentInterceptor)
  public async get(@ReqTenantAgent() tenantAgent: TenantAgent, @Param('did') did: string): Promise<DidDocumentDto> {
    const logger = this.logger.child('get', { did })
    logger.trace('>')

    const res = this.didService.get(tenantAgent, did)

    logger.trace({ res }, '<')
    return res
  }

  @ApiOperation({
    summary: 'Update a DID of the wallet',
    description:
      'Adds or removes services and Ed25519 verification methods (keys generated by the Identity Service) of a DID ' +
      'the wallet created. Supported for did:hedera and did:indybesu. The key that controls the DID cannot be changed.',
  })
  @ApiParam({ name: 'did', type: String })
  @ApiBody({ type: UpdateDidRequestDto })
  @ApiOkResponse({ description: 'Updated DID document', type: DidDocumentDto })
  @ApiBadRequestResponse({ description: 'Bad Request' })
  @ApiUnauthorizedResponse({ description: 'Unauthorized' })
  @ApiForbiddenResponse({ description: 'Forbidden' })
  @ApiNotFoundResponse({ description: 'The DID is not a DID of the wallet' })
  @ApiConflictResponse({ description: 'The DID is deactivated' })
  @ApiUnprocessableEntityResponse({ description: 'The method or the requested change is not supported' })
  @ApiServiceUnavailableResponse({
    description: 'The wallet is busy with another request, or the ledger of the DID cannot be read',
  })
  @Patch(':did')
  @Roles(Role.Admin, Role.OrgAdmin, Role.Issuer)
  @UseInterceptors(TenantAgentInterceptor)
  public async update(
    @ReqAuthInfo() authInfo: AuthInfo,
    @ReqTenantAgent() tenantAgent: TenantAgent,
    @Param('did') did: string,
    @Body() req: UpdateDidRequestDto,
  ): Promise<DidDocumentDto> {
    const logger = this.logger.child('update', { did })
    logger.trace('>')

    const res = await this.didService.update(authInfo, tenantAgent, did, req)

    logger.trace('<')
    return res
  }

  @ApiOperation({
    summary: 'Deactivate a DID of the wallet',
    description:
      'Deactivates a DID the wallet created, irreversibly. Supported for did:hedera and did:indybesu. ' +
      'Deactivating a deactivated DID returns it without a ledger write.',
  })
  @ApiParam({ name: 'did', type: String })
  @ApiOkResponse({ description: 'Deactivated DID document', type: DidDocumentDto })
  @ApiBadRequestResponse({ description: 'Bad Request' })
  @ApiUnauthorizedResponse({ description: 'Unauthorized' })
  @ApiForbiddenResponse({ description: 'Forbidden' })
  @ApiNotFoundResponse({ description: 'The DID is not a DID of the wallet' })
  @ApiConflictResponse({ description: 'Conflict' })
  @ApiUnprocessableEntityResponse({ description: 'The method does not support deactivation' })
  @ApiServiceUnavailableResponse({ description: 'The wallet is busy with another request' })
  @Post(':did/deactivate')
  @HttpCode(200)
  @Roles(Role.Admin, Role.OrgAdmin, Role.Issuer)
  @UseInterceptors(TenantAgentInterceptor)
  public async deactivate(
    @ReqAuthInfo() authInfo: AuthInfo,
    @ReqTenantAgent() tenantAgent: TenantAgent,
    @Param('did') did: string,
  ): Promise<DidDocumentDto> {
    const logger = this.logger.child('deactivate', { did })
    logger.trace('>')

    const res = await this.didService.deactivate(authInfo, tenantAgent, did)

    logger.trace('<')
    return res
  }
}
